-- One row per trip. Selects the columns marts need and adds a surrogate key.
select
        md5(concat_ws('|',
        license_num,
        dispatching_base,
        coalesce(cast(request_ts as string), ''),
        coalesce(cast(pickup_ts as string), ''),
        coalesce(cast(dropoff_ts as string), ''),
        cast(pu_location_id as string),
        cast(do_location_id as string),
        coalesce(cast(trip_miles as string), ''),
        coalesce(cast(base_passenger_fare as string), ''),
        coalesce(cast(driver_pay as string), ''),
        coalesce(cast(tips as string), '')
    )) as trip_id,
    company,
    license_num,
    request_ts,
    on_scene_ts,
    pickup_ts,
    dropoff_ts,
    pickup_date,
    pickup_hour,
    pu_location_id,
    do_location_id,
    trip_miles,
    trip_min,
    wait_min,
    speed_mph,
    base_passenger_fare,
    tolls,
    congestion_surcharge,
    cbd_congestion_fee,
    airport_fee,
    tips,
    driver_pay,
    fare_per_mile,
    driver_take_rate,
    is_shared_match,
    is_bad_wait,
    is_wait_outlier,
    is_zero_mile,
    is_adjustment,
    is_unknown_zone,
    is_impossible_speed
from {{ source('silver', 'hvfhv_trips') }}
